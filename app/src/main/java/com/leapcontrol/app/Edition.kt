package com.leapcontrol.app

/**
 * 版本分叉的**唯一开关** —— 全工程只在这里判一次，别在各个界面里散着写。
 *
 * ## 为什么要有它
 * 2026-11-15 起这个项目同时维护两条线：
 *  - **自用版**（`full`，私有仓库）：零跑官方 logo、登录页有标语、只在小圈子里用；
 *  - **个人学习版**（`personal`，公开仓库）：去掉全部品牌 logo 元素、去掉标语、
 *    「我的」页恢复支持作者与开源致谢、使用范围改为「仅限个人学习研究使用」。
 *
 * 两条线共用一份源码，差异全部收敛到 [PERSONAL_EDITION] 这一个布尔值：
 * 公开仓库只要在自己的 `gradle.properties` 里写 `leapcontrol.edition=personal`，
 * 同一个提交就能产出另一套包。**版本号（versionName / versionCode）天然同步**，
 * 不需要两边各改一次。
 *
 * ## 改动的边界（用户 2026-11-15 定）
 *  1. 零跑 logo 全部换成方向盘：桌面图标、登录页、桌面小组件左上角；
 *     「个性化 → 应用图标」整段不再出现（个人版没有第二套图标可选）。
 *  2. 登录页去掉「零跑控车，自在随行」标语。
 *  3. 小组件左上角车标换成方向盘图形。
 *  4. 「我的」页加回「支持作者」与「开源协议与致谢」两个入口。
 *  5. 使用范围改为「仅限个人学习研究使用，请在学习研究后及时卸载」。
 *  6. 版本号与自用版同步。
 *
 * 除此之外**不许再加差异**：两条线一旦在功能上分叉，这个开关就会变成第二个代码库。
 */
const val PERSONAL_EDITION: Boolean = BuildConfig.PERSONAL_EDITION

/**
 * 检查更新用的 GitHub 仓库（`owner/name`）。
 *
 * 自用版是私有仓库，检测与下载都要带只读令牌；个人学习版是公开仓库，
 * 匿名就能读 releases，所以它构建出来的包里 `GITHUB_TOKEN_ENCRYPTED` 是空的 ——
 * **公开的包绝不允许携带能读私有仓库的令牌**。
 */
val UPDATE_REPO: String = BuildConfig.UPDATE_REPO

/**
 * 车名兜底（用户还没给车起名时显示的那句）。
 *
 * 自用版是「我的零跑」；个人学习版不出现品牌名，一律叫「我的爱车」——
 * 小组件标题、小组件设置页里的预览、首页车名都从这里取，**别再各处写死**，
 * 否则会出现「方向盘车标配我的零跑」这种自相矛盾的画面。
 */
val DEFAULT_VEHICLE_TITLE: String = if (PERSONAL_EDITION) "我的爱车" else "我的零跑"
